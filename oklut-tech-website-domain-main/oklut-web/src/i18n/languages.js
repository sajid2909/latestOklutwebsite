export const RTL_LANGUAGES = new Set(['ar', 'ur', 'he', 'fa', 'ps', 'sd', 'yi'])

export function isRtlLanguage(code) {
  if (!code) return false
  const base = code.split('-')[0].toLowerCase()
  return RTL_LANGUAGES.has(base) || RTL_LANGUAGES.has(code.toLowerCase())
}

export const LANGUAGE_NAME_MAP = SUPPORTED_LANGUAGES.reduce((acc, cur) => {
  acc[cur.code] = cur.name
  return acc
}, {})
